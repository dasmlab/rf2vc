function detectLang() {
  const saved = localStorage.getItem(LANG_KEY);
  if (saved && I18N[saved]) return saved;
  return /^fr/i.test(navigator.language || "") ? "fr-CA" : "en";
}

let lang = detectLang();

function t(key, vars = {}) {
  const v = I18N[lang][key] ?? I18N.en[key] ?? key;
  if (typeof v === "function") return v(vars);
  return v.replace(/\{(\w+)\}/g, (_, k) => (vars[k] ?? `{${k}}`));
}

function tServer(msg) {
  if (lang !== "fr-CA" || !msg) return msg;
  for (const [re, fr] of SERVER_FR) {
    if (re.test(msg)) return msg.replace(re, fr);
  }
  return msg;
}

function tCheckName(name) {
  return lang === "fr-CA" ? (CHECK_NAMES_FR[name] || name) : name;
}

/** Translate data-i18n* attributes under root (document or a template fragment). */
function applyStaticI18n(root = document) {
  root.querySelectorAll("[data-i18n]").forEach(el => {
    el.textContent = t(el.dataset.i18n, el.dataset.i18nVars ? JSON.parse(el.dataset.i18nVars) : {});
  });
  root.querySelectorAll("[data-i18n-html]").forEach(el => { el.innerHTML = t(el.dataset.i18nHtml); });
  root.querySelectorAll("[data-i18n-title]").forEach(el => { el.title = t(el.dataset.i18nTitle); });
  root.querySelectorAll("[data-i18n-placeholder]").forEach(el => { el.placeholder = t(el.dataset.i18nPlaceholder); });
  root.querySelectorAll("[data-i18n-aria]").forEach(el => { el.setAttribute("aria-label", t(el.dataset.i18nAria)); });
}

